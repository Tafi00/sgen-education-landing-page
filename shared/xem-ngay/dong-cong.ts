export function getDongCong(ctx: DayContext): DongCongEntry | null {
  const month = (ctx.solarMonthBranch + 10) % 12;
  const row = TABLE[month]?.[sexagenaryIndex(ctx.day)];
  if (!row) return null;
  const [title, stars, rating, good] = row;
  const parts = [`Theo Đổng Công, ngày ${ctx.day.name} ${RATING_TEXT[rating]}`];
  if (stars) parts.push(`Ngày này gặp: ${stars}.`);
  return {
    title,
    label: stars || undefined,
    rating: RATINGS[rating],
    summary: parts.join(" "),
    suitable: good ? good.split(", ") : [],
  };
}
